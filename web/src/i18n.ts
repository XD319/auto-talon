export type TranslationKey = keyof typeof copy.en;

export function initialLocale(): Locale {
  const saved = window.localStorage.getItem("auto-talon.locale");
  if (saved === "en" || saved === "zh-CN") return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translate(locale: Locale, key: TranslationKey): string {
  return copy[locale][key];
}

export function formatTodayLine(
  locale: Locale,
  inboxCount: number,
  runningCount: number,
  budgetLabel: string | null
): string {
  const parts = [
    `${inboxCount} ${translate(locale, "inboxCount")}`,
    `${runningCount} ${translate(locale, "tasks")}`
  ];
  if (budgetLabel !== null && budgetLabel.length > 0) {
    parts.push(budgetLabel);
  }
  return parts.join(" · ");
}
